"""Create a B5 4K print image with oversampled Krea2 tile regeneration.

The source is first enlarged to a working canvas without generation.  Each
complete 256 px working tile is then resized to 1024 px, regenerated by Krea2,
and reduced as a complete tile to 512 px.  Overlapping 512 px results are
low-frequency anchored to a deterministic 2x base and feather-composited.
With the default 2x working canvas, a 1K source is drawn at roughly 4K and the
complete generated canvas is finally reduced to the B5 target dimensions.
"""

