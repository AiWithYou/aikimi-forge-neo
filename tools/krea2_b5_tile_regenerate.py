def validate_args(args: argparse.Namespace) -> None:
    if args.target_width <= 0 or args.target_height <= 0:
        raise ValueError("B5 target dimensions must be > 0")
    if args.tile_size <= 0 or args.process_edge <= args.tile_size:
        raise ValueError("process edge must be larger than tile size")
    if args.process_edge % 16 != 0:
        raise ValueError("process edge must be divisible by 16")
    if args.process_edge <= args.tile_size * 2:
        raise ValueError("process edge must be larger than the reduced output tile")
    if args.overlap < 0 or args.overlap >= args.tile_size:
        raise ValueError("overlap must satisfy 0 <= overlap < tile size")
    if args.steps <= 0:
        raise ValueError("steps must be > 0")
    if not 0 <= args.denoise <= 1:
        raise ValueError("denoise must be between 0 and 1")
    if args.timeout <= 0:
        raise ValueError("timeout must be > 0")
    for value, name in (
        (args.detail_radius, "detail radius"),
        (args.detail_gain, "detail gain"),
        (args.max_tile_delta, "maximum tile delta"),
        (args.structure_sigma, "structure sigma"),
        (args.base_detail_sigma, "base detail sigma"),
        (args.low_anchor_sigma, "low-frequency anchor sigma"),
        (args.print_detail_radius, "print detail radius"),
        (args.print_detail_threshold, "print detail threshold"),
        (args.print_max_detail_delta, "print maximum detail delta"),
    ):
        if not math.isfinite(float(value)) or float(value) <= 0:
            raise ValueError(f"{name} must be finite and > 0")
    if not 0 <= args.print_detail_strength <= 1:
        raise ValueError("print detail strength must be between 0 and 1")


def main() -> int:
    args = build_parser().parse_args()
    validate_args(args)
    if not args.input.is_file():
        raise FileNotFoundError(args.input)
    args.seed = resolve_seed(args.seed)
    with Image.open(args.input) as opened:
        opened.load()
        source_info = dict(opened.info)
        source = ImageOps.exif_transpose(opened).convert("RGB")
    if source.width < args.tile_size or source.height < args.tile_size:
        raise ValueError("input image is smaller than one complete source tile")
    validate_b5_aspect_ratio(
        source.size,
        (args.target_width, args.target_height),
    )
    generated_size = (
        source.width * args.working_scale * (2**args.stages),
        source.height * args.working_scale * (2**args.stages),
    )
    if max(generated_size) > 8192:
        raise ValueError(
            f"generated working canvas {generated_size[0]}x{generated_size[1]} "
            "exceeds the guarded 8192 px long-edge limit"
        )
    if generated_size[0] < args.target_width or generated_size[1] < args.target_height:
        raise ValueError(
            f"generated working canvas {generated_size[0]}x{generated_size[1]} is "
            f"smaller than target {args.target_width}x{args.target_height}; "
            "the final operation would enlarge instead of reduce"
        )
    png_prompt, _ = prompt_from_png(args.input)
    prompt = args.prompt if args.prompt is not None else LOCAL_TILE_PROMPT
    negative_prompt = args.negative_prompt if args.negative_prompt is not None else ""
    if args.append_guidance:
        prompt = krea2_detail_prompt(prompt)

    forge = validate_forge(args.api, min(args.timeout, 30.0))
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")
    incomplete_dir = args.output_root / f"_incomplete_b5_tiles_{stamp}"
    final_dir = args.output_root / f"b5_tiles_{stamp}"
    if incomplete_dir.exists() or final_dir.exists():
        raise FileExistsError("timestamped output directory already exists")
    incomplete_dir.mkdir(parents=True)
    work_dir = incomplete_dir / "work"
    work_dir.mkdir()
    required_bytes = estimate_temporary_bytes(
        source.size,
        working_scale=args.working_scale,
        stages=args.stages,
    )
    free_bytes = shutil.disk_usage(work_dir).free
    if free_bytes < required_bytes:
        remove_scoped_tree(incomplete_dir, expected_parent=args.output_root)
        raise RuntimeError(
            "Krea2 B5 tile regeneration needs about "
            f"{required_bytes / 1024**3:.2f} GiB of temporary disk space; "
            f"only {free_bytes / 1024**3:.2f} GiB is free"
        )
    started = time.perf_counter()
    manifest = {
        "format_version": 1,
        "algorithm": "Krea2 complete-tile oversampled B5 regeneration",
        "input": {
            "path": str(args.input),
            "sha256": file_sha256(args.input),
            "size": list(source.size),
        },
        "source_size": list(source.size),
        "working_input_size": [
            source.width * args.working_scale,
            source.height * args.working_scale,
        ],
        "generated_canvas_size": list(generated_size),
        "target_size": [args.target_width, args.target_height],
        "tile_size": args.tile_size,
        "process_edge": args.process_edge,
        "reduced_tile_size": args.tile_size * 2,
        "overlap": args.overlap,
        "working_scale": args.working_scale,
        "stages": args.stages,
        "steps": args.steps,
        "denoise": args.denoise,
        "detail_filter": {
            "mode": args.merge_mode,
            "low_anchor_sigma": args.low_anchor_sigma,
            "radius": args.detail_radius,
            "gain": args.detail_gain,
            "maximum_delta": args.max_tile_delta,
            "structure_sigma": args.structure_sigma,
            "base_detail_sigma": args.base_detail_sigma,
        },
        "seed": args.seed,
        "source_prompt_sha256": hashlib.sha256(png_prompt.encode("utf-8")).hexdigest(),
        "prompt_sha256": hashlib.sha256(prompt.encode("utf-8")).hexdigest(),
        "negative_prompt_sha256": hashlib.sha256(
            negative_prompt.encode("utf-8")
        ).hexdigest(),
        "forge": forge,
        "protection_regions": [asdict(value) for value in args.protect_ellipse],
        "stage_reports": [],
    }
    try:
        current = source.resize(
            (
                source.width * args.working_scale,
                source.height * args.working_scale,
            ),
            Image.Resampling.LANCZOS,
        )
        for stage_index in range(args.stages):
            current, stage_report = regenerate_stage(
                current,
                args,
                prompt=prompt,
                negative_prompt=negative_prompt,
                global_seed=args.seed,
                original_size=source.size,
                original_regions=list(args.protect_ellipse),
                stage_index=stage_index,
                work_dir=work_dir,
                output_dir=incomplete_dir,
            )
            manifest["stage_reports"].append(stage_report)
            (incomplete_dir / "run_manifest.json").write_text(
                json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
            )

        final = current.resize(
            (args.target_width, args.target_height), Image.Resampling.LANCZOS
        )
        final, print_finish = adaptive_detail_guard(
            final,
            strength=args.print_detail_strength,
            radius=args.print_detail_radius,
            detail_threshold=args.print_detail_threshold,
            max_detail_delta=args.print_max_detail_delta,
        )
        final_base = source.resize(
            (args.target_width, args.target_height),
            Image.Resampling.LANCZOS,
        )
        final_regions = scale_protection_regions_xy(
            list(args.protect_ellipse),
            args.target_width / source.width,
            args.target_height / source.height,
        )
        final, final_protection = apply_stage_protection(
            final,
            final_base,
            final_regions,
        )
        dpi = args.target_height / (B5_HEIGHT_MM / 25.4)
        manifest["print_finish"] = print_finish
        manifest["final_protection"] = final_protection
        manifest["b5_print"] = {
            "trim_mm": [182, 257],
            "pixel_size": [args.target_width, args.target_height],
            "effective_dpi_from_height": dpi,
            "color_space": "sRGB pixels; no printer-specific ICC conversion",
        }
        manifest["elapsed_seconds"] = time.perf_counter() - started
        summary = {
            "format_version": 1,
            "source_size": list(source.size),
            "target_size": [args.target_width, args.target_height],
            "tile_size": args.tile_size,
            "process_edge": args.process_edge,
            "stages": args.stages,
            "seed": args.seed,
            "protected_region_count": len(args.protect_ellipse),
            "effective_dpi": dpi,
        }
        output_name = f"{args.input.stem}_b5_4k.png"
        output_path = incomplete_dir / output_name
        final.save(
            output_path,
            format="PNG",
            pnginfo=pnginfo_for_output(source_info, summary),
            dpi=(dpi, dpi),
            optimize=True,
        )
        manifest["output"] = {
            "path": str(final_dir / output_name),
            "sha256": file_sha256(output_path),
            "size": [args.target_width, args.target_height],
        }
        remove_scoped_tree(work_dir, expected_parent=incomplete_dir)
        (incomplete_dir / "run_manifest.json").write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        incomplete_dir.rename(final_dir)
        emit(f"OUTPUT_DIR={final_dir}")
        emit(f"IMAGE={final_dir / output_name}")
        emit(f"MANIFEST={final_dir / 'run_manifest.json'}")
        emit(f"DPI={dpi:.3f}")
        return 0
    except BaseException:
        if incomplete_dir.exists():
            remove_scoped_tree(incomplete_dir, expected_parent=args.output_root)
        raise


if __name__ == "__main__":
    raise SystemExit(main())
