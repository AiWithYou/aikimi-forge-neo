def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(4 * 1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def resolve_seed(seed: int) -> int:
    if seed < -1 or seed >= 2**32:
        raise ValueError("--seed must be -1 or a non-negative 32-bit integer")
    return secrets.randbelow(2**32) if seed == -1 else seed


def tile_origins(length: int, tile_size: int, overlap: int) -> list[int]:
    """Return balanced origins that cover an axis with complete overlapping tiles."""

    length = int(length)
    tile_size = int(tile_size)
    overlap = int(overlap)
    if length < tile_size:
        raise ValueError("canvas axis must be at least one complete tile")
    if overlap < 0 or overlap >= tile_size:
        raise ValueError("tile overlap must satisfy 0 <= overlap < tile size")
    if length == tile_size:
        return [0]
    stride = tile_size - overlap
    count = int(math.ceil((length - tile_size) / stride)) + 1
    return [
        int(round(index * (length - tile_size) / (count - 1))) for index in range(count)
    ]


def axis_blend_weight(
    length: int,
    feather: int,
    *,
    touches_start: bool,
    touches_end: bool,
) -> np.ndarray:
    if length <= 0:
        raise ValueError("weight length must be > 0")
    if feather < 0:
        raise ValueError("weight feather must be >= 0")
    feather = min(int(feather), length // 2)
    weight = np.ones(length, dtype=np.float32)
    if feather == 0:
        return weight
    position = (np.arange(feather, dtype=np.float32) + 0.5) / feather
    ramp = position * position * (3.0 - 2.0 * position)
    if not touches_start:
        weight[:feather] = ramp
    if not touches_end:
        weight[-feather:] = ramp[::-1]
    return weight


def tile_blend_weight(
    tile_size: int,
    feather: int,
    *,
    x0: int,
    y0: int,
    canvas_size: tuple[int, int],
) -> np.ndarray:
    canvas_width, canvas_height = canvas_size
    x_weight = axis_blend_weight(
        tile_size,
        feather,
        touches_start=x0 == 0,
        touches_end=x0 + tile_size == canvas_width,
    )
    y_weight = axis_blend_weight(
        tile_size,
        feather,
        touches_start=y0 == 0,
        touches_end=y0 + tile_size == canvas_height,
    )
    return y_weight[:, None] * x_weight[None, :]


def image_to_b64_png(image: Image.Image) -> str:
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    return base64.b64encode(buffer.getvalue()).decode("ascii")


def decode_b64_image(value: str) -> Image.Image:
    payload = value.split(",", 1)[-1]
    with Image.open(io.BytesIO(base64.b64decode(payload))) as opened:
        return opened.convert("RGB")


def source_gated_detail(
    candidate: Image.Image,
    base: Image.Image,
    *,
    radius: int,
    gain: float,
    max_delta: float,
    structure_sigma: float,
    base_detail_sigma: float,
) -> tuple[Image.Image, dict[str, float]]:
    """Keep only source-supported regenerated high-frequency detail."""

    if candidate.size != base.size:
        raise ValueError("candidate and base tile sizes must match")
    base_values = np.asarray(base.convert("RGB"), dtype=np.float32)
    delta, gate_report = frequency_detail_delta(
        np.asarray(candidate.convert("RGB"), dtype=np.uint8),
        np.asarray(base.convert("RGB"), dtype=np.uint8),
        radius=radius,
        gain=gain,
        max_delta=max_delta,
        structure_sigma=structure_sigma,
        base_detail_sigma=base_detail_sigma,
    )
    result_values = np.clip(np.rint(base_values + delta), 0, 255).astype(np.uint8)
    report = {
        "mean_abs_rgb_delta": float(np.mean(np.abs(delta), dtype=np.float64)),
        "p95_abs_rgb_delta": float(np.percentile(np.abs(delta), 95.0)),
        "max_abs_rgb_delta": float(np.max(np.abs(delta))),
        "clipped_delta_fraction": gate_report["clipped_fraction"],
        **gate_report,
    }
    return Image.fromarray(result_values), report


def low_frequency_detail(
    candidate: Image.Image,
    base: Image.Image,
    *,
    sigma: float,
    max_delta: float,
) -> tuple[Image.Image, dict[str, float]]:
    """Keep bounded regenerated detail while replacing the candidate low band."""

    if candidate.size != base.size:
        raise ValueError("candidate and base tile sizes must match")
    if not math.isfinite(float(sigma)) or sigma <= 0:
        raise ValueError("low-frequency sigma must be > 0")
    if not math.isfinite(float(max_delta)) or max_delta <= 0:
        raise ValueError("maximum tile delta must be > 0")
    candidate_values = np.asarray(candidate.convert("RGB"), dtype=np.float32)
    base_values = np.asarray(base.convert("RGB"), dtype=np.float32)
    candidate_low = cv2.GaussianBlur(
        candidate_values,
        (0, 0),
        sigmaX=float(sigma),
        sigmaY=float(sigma),
        borderType=cv2.BORDER_REFLECT_101,
    )
    base_low = cv2.GaussianBlur(
        base_values,
        (0, 0),
        sigmaX=float(sigma),
        sigmaY=float(sigma),
        borderType=cv2.BORDER_REFLECT_101,
    )
    anchored = candidate_values + (base_low - candidate_low)
    raw_delta = anchored - base_values
    delta = np.clip(raw_delta, -float(max_delta), float(max_delta))
    result_values = np.clip(np.rint(base_values + delta), 0, 255).astype(np.uint8)
    return Image.fromarray(result_values), {
        "mean_abs_rgb_delta": float(np.mean(np.abs(delta), dtype=np.float64)),
        "p95_abs_rgb_delta": float(np.percentile(np.abs(delta), 95.0)),
        "max_abs_rgb_delta": float(np.max(np.abs(delta))),
        "clipped_delta_fraction": float(np.mean(np.abs(raw_delta) >= float(max_delta))),
    }


def scale_protection_regions(
    regions: list[ProtectionEllipse],
    scale: float,
) -> list[ProtectionEllipse]:
    if not math.isfinite(float(scale)) or scale <= 0:
        raise ValueError("protection scale must be > 0")
    return [
        ProtectionEllipse(
            label=region.label,
            box=tuple(int(round(value * scale)) for value in region.box),
            feather=max(1, int(round(region.feather * scale))),
        )
        for region in regions
    ]


def scale_protection_regions_xy(
    regions: list[ProtectionEllipse],
    x_scale: float,
    y_scale: float,
) -> list[ProtectionEllipse]:
    """Scale source-coordinate ellipses to a potentially non-uniform target."""

    if not math.isfinite(float(x_scale)) or x_scale <= 0:
        raise ValueError("protection x scale must be > 0")
    if not math.isfinite(float(y_scale)) or y_scale <= 0:
        raise ValueError("protection y scale must be > 0")
    feather_scale = min(float(x_scale), float(y_scale))
    return [
        ProtectionEllipse(
            label=region.label,
            box=(
                int(round(region.box[0] * x_scale)),
                int(round(region.box[1] * y_scale)),
                int(round(region.box[2] * x_scale)),
                int(round(region.box[3] * y_scale)),
            ),
            feather=max(1, int(round(region.feather * feather_scale))),
        )
        for region in regions
    ]


def validate_b5_aspect_ratio(
    source_size: tuple[int, int],
    target_size: tuple[int, int] = DEFAULT_TARGET_SIZE,
    *,
    relative_tolerance: float = B5_ASPECT_REL_TOLERANCE,
) -> None:
    """Reject inputs that would be visibly distorted by the final B5 resize."""

    source_width, source_height = map(int, source_size)
    target_width, target_height = map(int, target_size)
    if min(source_width, source_height, target_width, target_height) <= 0:
        raise ValueError("source and target dimensions must be > 0")
    if not math.isfinite(float(relative_tolerance)) or relative_tolerance < 0:
        raise ValueError("aspect-ratio tolerance must be finite and >= 0")
    source_ratio = source_width / source_height
    target_ratio = target_width / target_height
    if not math.isclose(
        source_ratio,
        target_ratio,
        rel_tol=float(relative_tolerance),
        abs_tol=0.0,
    ):
        raise ValueError(
            "input aspect ratio must already match portrait JIS B5 within "
            f"{relative_tolerance * 100:.1f}% to avoid geometric distortion; "
            f"got {source_width}x{source_height} for target "
            f"{target_width}x{target_height}"
        )


def estimate_temporary_bytes(
    source_size: tuple[int, int],
    *,
    working_scale: int,
    stages: int,
) -> int:
    """Estimate stage memmaps and intermediate PNG storage with safety margin."""

    width = int(source_size[0]) * int(working_scale)
    height = int(source_size[1]) * int(working_scale)
    total = 0
    for _ in range(int(stages)):
        width *= 2
        height *= 2
        pixels = width * height
        total += pixels * (3 * 4 + 4 + 3 + 3)
    return int(math.ceil(total * 1.25 + 512 * 1024**2))


def apply_stage_protection(
    candidate: Image.Image,
    deterministic_base: Image.Image,
    regions: list[ProtectionEllipse],
) -> tuple[Image.Image, dict | None]:
    if not regions:
        return candidate, None
    mask, report = protection_mask(candidate.size, regions)
    return Image.composite(deterministic_base, candidate, mask), report


def request_json(
    method: str, url: str, *, timeout: float, payload: dict | None = None
) -> dict:
    response = requests.request(method, url, timeout=timeout, json=payload)
    if response.status_code >= 400:
        detail = response.text[:1500].replace("\n", " ")
        raise RuntimeError(f"Forge API {response.status_code} for {url}: {detail}")
    value = response.json()
    if not isinstance(value, dict):
        raise RuntimeError(f"Forge returned a non-object response for {url}")
    return value


def validate_forge(api: str, timeout: float) -> dict:
    options = request_json(
        "GET", f"{api.rstrip('/')}/sdapi/v1/options", timeout=timeout
    )
    checkpoint = Path(str(options.get("sd_model_checkpoint") or "")).name
    normalized_checkpoint = "".join(
        character for character in checkpoint.casefold() if character.isalnum()
    )
    if "krea2" not in normalized_checkpoint:
        raise RuntimeError(
            "Forge must have a Krea2 checkpoint selected before tile regeneration"
        )
    additional = options.get("forge_additional_modules") or []
    if isinstance(additional, str):
        additional = [additional]
    normalized_modules = [
        "".join(
            character
            for character in Path(str(value)).name.casefold()
            if character.isalnum()
        )
        for value in additional
    ]
    if not any("qwenimagevae" in value for value in normalized_modules):
        raise RuntimeError("Krea2 tile regeneration requires qwen_image_vae")
    if not any("qwen3vl" in value for value in normalized_modules):
        raise RuntimeError("Krea2 tile regeneration requires a qwen3vl text encoder")
    return {
        "checkpoint": checkpoint,
        "additional_modules": [Path(str(value)).name for value in additional],
    }


def regenerate_tile(
    tile: Image.Image,
    *,
    api: str,
    prompt: str,
    negative_prompt: str,
    seed: int,
    steps: int,
    denoise: float,
    sampler: str,
    scheduler: str,
    cfg: float,
    shift: float,
    process_edge: int,
    output_edge: int,
    timeout: float,
) -> tuple[Image.Image, float]:
    process_input = tile.resize((process_edge, process_edge), Image.Resampling.LANCZOS)
    payload = {
        "init_images": [image_to_b64_png(process_input)],
        "prompt": prompt,
        "negative_prompt": negative_prompt,
        "seed": seed,
        "sampler_name": sampler,
        "scheduler": scheduler,
        "steps": steps,
        "cfg_scale": cfg,
        "distilled_cfg_scale": shift,
        "width": process_edge,
        "height": process_edge,
        "resize_mode": 0,
        "denoising_strength": denoise,
        "n_iter": 1,
        "batch_size": 1,
        "restore_faces": False,
        "tiling": False,
        "send_images": True,
        "save_images": False,
        "include_init_images": False,
        "override_settings": {"img2img_fix_steps": True},
        "override_settings_restore_afterwards": True,
    }
    started = time.perf_counter()
    response = request_json(
        "POST",
        f"{api.rstrip('/')}/sdapi/v1/img2img",
        timeout=timeout,
        payload=payload,
    )
    elapsed = time.perf_counter() - started
    images = response.get("images") or []
    if not images:
        raise RuntimeError("Forge returned no regenerated tile")
    regenerated = decode_b64_image(images[0])
    if regenerated.size != (process_edge, process_edge):
        raise RuntimeError(
            f"Forge returned tile {regenerated.size}; expected {process_edge}x{process_edge}"
        )
    return (
        regenerated.resize((output_edge, output_edge), Image.Resampling.LANCZOS),
        elapsed,
    )


def close_memmap(values: np.memmap | None) -> None:
    if values is None:
        return
    values.flush()
    mmap = getattr(values, "_mmap", None)
    if mmap is not None:
        mmap.close()


def remove_scoped_tree(path: Path, *, expected_parent: Path) -> None:
    """Remove one known child directory after resolving its exact scope."""

    resolved_path = path.resolve(strict=False)
    resolved_parent = expected_parent.resolve(strict=False)
    if resolved_path.parent != resolved_parent:
        raise RuntimeError(
            f"refusing to remove directory outside expected parent: {resolved_path}"
        )
    if resolved_path == resolved_parent:
        raise RuntimeError(f"refusing to remove parent directory: {resolved_path}")
    if resolved_path.exists():
        shutil.rmtree(resolved_path)


def regenerate_stage(
    source: Image.Image,
    args: argparse.Namespace,
    *,
    prompt: str,
    negative_prompt: str,
    global_seed: int,
    original_size: tuple[int, int],
    original_regions: list[ProtectionEllipse],
    stage_index: int,
    work_dir: Path,
    output_dir: Path,
    tile_regenerator: Callable[..., tuple[Image.Image, float]] = regenerate_tile,
    progress_callback: Callable[[dict], None] | None = None,
    interrupted: Callable[[], bool] | None = None,
    save_stage: bool = True,
) -> tuple[Image.Image, dict]:
    stage_number = stage_index + 1
    source_width, source_height = source.size
    target_size = (source_width * 2, source_height * 2)
    deterministic_base = source.resize(target_size, Image.Resampling.LANCZOS)
    input_origins_x = tile_origins(source_width, args.tile_size, args.overlap)
    input_origins_y = tile_origins(source_height, args.tile_size, args.overlap)
    total_tiles = len(input_origins_x) * len(input_origins_y)
    output_tile_size = args.tile_size * 2
    output_feather = args.overlap * 2
    accumulator_path = work_dir / f"stage_{stage_number:02d}_rgb.float32"
    weight_path = work_dir / f"stage_{stage_number:02d}_weight.float32"
    accumulator = np.memmap(
        accumulator_path,
        dtype=np.float32,
        mode="w+",
        shape=(target_size[1], target_size[0], 3),
    )
    weight_sum = np.memmap(
        weight_path,
        dtype=np.float32,
        mode="w+",
        shape=(target_size[1], target_size[0]),
    )
    accumulator[:] = 0.0
    weight_sum[:] = 0.0
    records = []
    stage_started = time.perf_counter()
    try:
        sequence = 0
        for input_y0 in input_origins_y:
            for input_x0 in input_origins_x:
                if interrupted is not None and interrupted():
                    raise RuntimeError(
                        "Krea2 B5 tile regeneration was interrupted before completion"
                    )
                sequence += 1
                tile = source.crop(
                    (
                        input_x0,
                        input_y0,
                        input_x0 + args.tile_size,
                        input_y0 + args.tile_size,
                    )
                )
                output_x0 = input_x0 * 2
                output_y0 = input_y0 * 2
                base_tile = deterministic_base.crop(
                    (
                        output_x0,
                        output_y0,
                        output_x0 + output_tile_size,
                        output_y0 + output_tile_size,
                    )
                )
                tile_seed = coordinate_seed(
                    global_seed,
                    stage_number,
                    input_x0,
                    input_y0,
                )
                emit(
                    f"STAGE={stage_number}/{args.stages} TILE={sequence}/{total_tiles} "
                    f"INPUT={input_x0},{input_y0},{args.tile_size}x{args.tile_size} "
                    f"PROCESS={args.process_edge} OUTPUT={output_tile_size} "
                    f"DENOISE={args.denoise:.3f} SEED={tile_seed}"
                )
                if progress_callback is not None:
                    progress_callback(
                        {
                            "stage": stage_number,
                            "stages": args.stages,
                            "tile": sequence,
                            "tiles": total_tiles,
                            "input_x": input_x0,
                            "input_y": input_y0,
                            "process_edge": args.process_edge,
                            "steps": args.steps,
                            "denoise": args.denoise,
                        }
                    )
                regenerated, elapsed = tile_regenerator(
                    tile,
                    api=args.api,
                    prompt=prompt,
                    negative_prompt=negative_prompt,
                    seed=tile_seed,
                    steps=args.steps,
                    denoise=args.denoise,
                    sampler=args.sampler,
                    scheduler=args.scheduler,
                    cfg=args.cfg,
                    shift=args.shift,
                    process_edge=args.process_edge,
                    output_edge=output_tile_size,
                    timeout=args.timeout,
                )
                if args.merge_mode == "low_anchor":
                    anchored, anchor_report = low_frequency_detail(
                        regenerated,
                        base_tile,
                        sigma=args.low_anchor_sigma,
                        max_delta=args.max_tile_delta,
                    )
                else:
                    anchored, anchor_report = source_gated_detail(
                        regenerated,
                        base_tile,
                        radius=args.detail_radius,
                        gain=args.detail_gain,
                        max_delta=args.max_tile_delta,
                        structure_sigma=args.structure_sigma,
                        base_detail_sigma=args.base_detail_sigma,
                    )
                weight = tile_blend_weight(
                    output_tile_size,
                    output_feather,
                    x0=output_x0,
                    y0=output_y0,
                    canvas_size=target_size,
                )
                output_slice = np.s_[
                    output_y0 : output_y0 + output_tile_size,
                    output_x0 : output_x0 + output_tile_size,
                ]
                accumulator[output_slice] += (
                    np.asarray(anchored, dtype=np.float32) * weight[..., None]
                )
                weight_sum[output_slice] += weight
                records.append(
                    {
                        "sequence": sequence,
                        "input_box": [
                            input_x0,
                            input_y0,
                            input_x0 + args.tile_size,
                            input_y0 + args.tile_size,
                        ],
                        "output_box": [
                            output_x0,
                            output_y0,
                            output_x0 + output_tile_size,
                            output_y0 + output_tile_size,
                        ],
                        "seed": tile_seed,
                        "elapsed_seconds": elapsed,
                        "anchor": anchor_report,
                    }
                )
                emit(
                    f"STAGE={stage_number}/{args.stages} TILE={sequence}/{total_tiles} "
                    f"DONE={elapsed:.2f}s DELTA_MEAN={anchor_report['mean_abs_rgb_delta']:.3f}"
                )
        accumulator.flush()
        weight_sum.flush()
        if float(np.min(weight_sum)) <= 0.0:
            raise RuntimeError("tile blend left uncovered output pixels")

        result_path = work_dir / f"stage_{stage_number:02d}_result.uint8"
        result_values = np.memmap(
            result_path,
            dtype=np.uint8,
            mode="w+",
            shape=(target_size[1], target_size[0], 3),
        )
        try:
            for y0 in range(0, target_size[1], 256):
                y1 = min(target_size[1], y0 + 256)
                normalized = (
                    np.asarray(accumulator[y0:y1], dtype=np.float32)
                    / np.asarray(weight_sum[y0:y1], dtype=np.float32)[..., None]
                )
                result_values[y0:y1] = np.clip(np.rint(normalized), 0, 255).astype(
                    np.uint8
                )
            result_values.flush()
            result = Image.fromarray(np.asarray(result_values).copy())
        finally:
            close_memmap(result_values)

        scale = target_size[0] / original_size[0]
        stage_regions = scale_protection_regions(original_regions, scale)
        result, protection_report = apply_stage_protection(
            result,
            deterministic_base,
            stage_regions,
        )
        stage_path = None
        if save_stage:
            stage_path = (
                output_dir
                / f"stage_{stage_number:02d}_{target_size[0]}x{target_size[1]}.png"
            )
            result.save(stage_path, format="PNG", optimize=True)
        return result, {
            "stage": stage_number,
            "source_size": [source_width, source_height],
            "target_size": list(target_size),
            "tile_size": args.tile_size,
            "process_edge": args.process_edge,
            "output_tile_size": output_tile_size,
            "overlap": args.overlap,
            "output_overlap": output_feather,
            "tile_count": total_tiles,
            "elapsed_seconds": time.perf_counter() - stage_started,
            "protection": protection_report,
            "output": str(stage_path) if stage_path is not None else None,
            "tiles": records,
        }
    finally:
        close_memmap(accumulator)
        close_memmap(weight_sum)


def pnginfo_for_output(source_info: dict, summary: dict) -> PngImagePlugin.PngInfo:
    pnginfo = PngImagePlugin.PngInfo()
    for key, value in source_info.items():
        if isinstance(value, str) and key not in {
            "parameters",
            "krea2_b5_tile_regenerate",
        }:
            pnginfo.add_text(key, value)
    parameters = str(source_info.get("parameters") or "")
    if parameters:
        source_size = tuple(summary["source_size"])
        target_size = tuple(summary["target_size"])
        parameters = replace_infotext_size(
            parameters,
            source_size[0],
            source_size[1],
            target_size[0],
            target_size[1],
        )
        parameters += (
            f", Krea2 B5 Tile Regenerate: {summary['tile_size']}->"
            f"{summary['process_edge']}->{summary['tile_size'] * 2}, "
            f"Stages: {summary['stages']}"
        )
        pnginfo.add_text("parameters", parameters)
    pnginfo.add_text(
        "krea2_b5_tile_regenerate",
        json.dumps(summary, ensure_ascii=False, separators=(",", ":")),
    )
    return pnginfo


